import mongoose from 'mongoose';

const PassengerSchema = new mongoose.Schema({
  PassengerID: String,
  PassengerType: { type: String, enum: ['Adult', 'Child', 'Infant'], default: 'Adult' },
  Title: String,
  FirstName: String,
  LastName: String,
  PersianFirstName: { type: String, default: '' },
  PersianLastName: { type: String, default: '' },
  Gender: String,
  DOB: String,
  Nationality: { type: String, default: 'PAK' },
  NationalId: { type: String, default: '' },
  PassportNumber: String,
  PassportIssueDate: String,
  PassportExpiryDate: String,
  TicketNumber: { type: String, default: '' },
  WithAdult: { type: String, default: '' },
  SSRCode: { type: String, default: 'TKNE' },
  PassportImageName: { type: String, default: '' },
  PassportFileData: { type: String, default: '' }
});

