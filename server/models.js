export const SegmentModel = mongoose.models.Segment || mongoose.model('Segment', SegmentSchema);
export const FlightGroupModel = mongoose.models.FlightGroup || mongoose.model('FlightGroup', FlightGroupSchema);
export const BookingModel = mongoose.models.Booking || mongoose.model('Booking', BookingSchema);
export const SubAgentModel = mongoose.models.SubAgent || mongoose.model('SubAgent', SubAgentSchema);
